const skel = fs.readFileSync(SKELETON, 'utf8');
const headEnd = skel.indexOf('</header>') + '</header>'.length;
const footStart = skel.indexOf('<footer class="mh-footer">');
const HEAD = skel.slice(0, headEnd);
const TAIL = skel.slice(footStart);

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function card(slug) {
  return `      <a href="../services/procedures/${slug}.html" class="prob-card">
        <span class="prob-card__frame"><img src="../assets/photos/${PHOTO[slug]}.webp" alt="${esc(PROC[slug])} в клинике RA|RÉ" loading="lazy" decoding="async"/></span>
        <span class="prob-card__title">${esc(PROC[slug])}</span>
      </a>`;
}

function build(p) {
  const parts = [];
  parts.push(`<nav class="article-bc wrap" aria-label="Хлебные крошки">
  <a href="../index.html">Главная</a><span>›</span>
  <a href="../index.html#wish">Я хочу</a><span>›</span>
  <span class="article-bc__current">${esc(p.h1)}</span>
</nav>`);
  parts.push(`<section class="article-top wrap">
  <h1 class="article-title-simple">${esc(p.h1)}</h1>
</section>`);

  const blocks = [`    <div class="article-section"><p>${esc(p.intro)}</p></div>`];
  if (p.list) {
    blocks.push(`    <div class="article-section">
      <h3>${esc(p.list.h)}</h3>
      <ul class="prob-list">${p.list.items.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>
    </div>`);
  }
  for (const s of p.sections) {
    blocks.push(`    <div class="article-section">
      <h3>${esc(s.h)}</h3>
      <p>${esc(s.p)}</p>
    </div>`);
  }
  parts.push(`<section class="article-content-wrap wrap">
  <div class="article-content">
${blocks.join('\n')}
  </div>
</section>`);

  parts.push(`<section class="prob-procs wrap">
  <h2 class="prob-procs__heading">Что поможет</h2>
  <div class="prob-procs__grid">
${p.procs.map(card).join('\n')}
  </div>
  <a href="../services.html" class="prob-procs__all">Все услуги клиники</a>
</section>`);

  let html = HEAD + '\n\n' + parts.join('\n\n') + '\n\n' + TAIL;
  html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(p.h1)} — RA|RÉ Клиника экспертной косметологии в Анапе</title>`);
  html = html.replace(/<link rel="canonical" href="[^"]*"\/>/, `<link rel="canonical" href="https://rare.a-4-to.ru/${OUT}/${p.slug}.html"/>`);
  html = html.replace(/<meta name="description" content="[^"]*"\/>/, `<meta name="description" content="${esc(p.desc)}"/>`);
  html = html.replace(/<link rel="stylesheet" href="\.\.\/css\/pages\/article-detail\.css[^"]*"\/>/,
    `<link rel="stylesheet" href="../css/pages/article-detail.css?v=202609110100"/>\n<link rel="stylesheet" href="../css/pages/problems.css?v=202610021500"/>`);
  html = html.replace('<body class="page page--article-detail">', '<body class="page page--problem">');
  html = html.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\n/g, '');
  html = html.replace(/<!-- schema:auto[\s\S]*?<!-- \/schema:auto -->\n/, '');
  html = html.replace(/[ \t]*<script src="\.\.\/js\/video-loading\.js[^"]*"[^>]*><\/script>\n/, '');
  return html;
}

if (!check && !fs.existsSync(OUT)) fs.mkdirSync(OUT);
let n = 0;
for (const p of PAGES) {
  const file = path.join(OUT, p.slug + '.html');
  const html = build(p);
  if (!check) fs.writeFileSync(file, html);
  n++;
  console.log(`  ${file}  ${p.procs.length} процедур, ${html.length} символов`);
}
console.log(`${check ? 'Будет создано' : 'Создано'} страниц: ${n}`);

